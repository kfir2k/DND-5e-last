// ---- Patterns: casting-time / range strings that carry numbers ----
(function(){
  const shape={cone:'חרוט',line:'קו',cube:'קובייה',dome:'כיפה'};
  I18N_HE_RX.push(
    // "1 Minute (Ritual)", "1 Action (Ritual)" — the time word is translated by the entries above
    [/^(.+) \(Ritual\)$/,(m,tr)=>/^\d+ (Action|Bonus Action|Reaction|Minutes?|Hours?)$/.test(m[1])?`${tr(m[1])} (טקס)`:null],
    // "Self 5ft" (a burst around you), "Self 15ft cone", "Self 30ft line", "Self 5mi"
    [/^Self (\d+)ft(?: (cone|line|cube|dome))?$/,m=>m[2]?`עצמי (${shape[m[2]]} של ${m[1]} רגל)`:`עצמי (רדיוס ${m[1]} רגל)`],
    [/^Self (\d+)mi$/,m=>`עצמי (רדיוס ${m[1]} מייל)`],
    [/^(\d+) miles?$/,m=>+m[1]===1?'מייל אחד':`${m[1]} מייל`],
    [/^Level (\d+)$/,m=>`רמה ${m[1]}`],
    // the spell modal's "WIS Save" line (built from the description's "(Wis save)")
    [/^(STR|DEX|CON|INT|WIS|CHA) Save$/,m=>`הצלת ${({STR:'כוח',DEX:'זריזות',CON:'חוסן',INT:'אינטליגנציה',WIS:'חוכמה',CHA:'כריזמה'})[m[1]]}`],
  );
})();

