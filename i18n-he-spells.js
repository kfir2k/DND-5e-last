// Hebrew translations of SPELL data: the facts tables (school, casting time, range, duration), then
// spell names and their one-line descriptions, grouped by spell level. Loaded after i18n-he.js (which
// defines heAdd / I18N_HE_RX / heN) and before i18n.js.
//
// Style, so every entry reads like the same hand wrote it (the glossary is tools/i18n-terms.js):
//  · The English descriptions are terse notes, so the Hebrew is too: noun phrases and infinitives, not
//    full sentences. Avoid second-person VERBS (they are gendered); the possessive suffix ך ("שלך",
//    "לעברך") is spelled the same for everyone, so it is fine.
//  · Dice, numbers and DC stay exactly as written (1d6, 5, DC) — the checker compares them.
//  · Damage and conditions use the same word as the rest of the app ("נזק אש", "שרוע"); a saving throw
//    is "הצלת <תכונה>" with the Hebrew ability name; "5th character level" is "ברמת דמות 5".
//  · Spell names are Hebrew only (the owner's choice). Run `node tools/i18n-check.js` after editing.

