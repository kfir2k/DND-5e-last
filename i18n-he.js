// Hebrew UI dictionary — English text as it appears in the interface → Hebrew. Keys are matched
// exactly (whitespace collapsed); values are what gets shown. Game data (spells, features, items,
// class/race names and descriptions) is deliberately not here — see i18n.js.
//
// Conventions (so the whole UI reads as one voice):
//  · Masculine imperative for buttons/instructions ("הוסף", "בחר", "הקש") — the usual UI register.
//  · HP, AC, DC, the ability abbreviations (STR/DEX/CON/INT/WIS/CHA), dice notation (d20, 2d6), coin
//    abbreviations (CP/SP/EP/GP/PP) and the formula words PROF / LVL stay in Latin: players say them
//    that way at the table, and PROF/LVL/STR… are tokens the app actually parses in formula fields.
//  · Terms: class מקצוע · subclass תת-מקצוע · race גזע · heritage מורשת · background רקע ·
//    feature יכולת · feat כישרון · spell כישוף · cantrip קנטריפ · spell slot משבצת כישוף ·
//    proficiency מיומנות · expertise מומחיות · saving throw הטלת הצלה · advantage/disadvantage יתרון/חיסרון.
//  · Text is split exactly where the app splits it into DOM nodes: a paragraph with bold/italic
//    pieces has one entry per piece, written so the pieces still read in order.
//
// I18N_HE      exact string → Hebrew
// I18N_HE_RX   [regex, (match, tr) => Hebrew] for sentences with numbers/names inside; tr() translates a
//              captured piece (a skill name, a stat…) through this same dictionary
// I18N_HE_KEEP strings that stay as they are and shouldn't be reported as untranslated
const I18N_HE={};
const I18N_HE_RX=[];
const I18N_HE_KEEP=[
  'game-icons.net',
  '(CC BY 3.0) — Lorc, Delapouite, Skoll, sbed, carl-olsen.',
];
// The GAME-DATA translations (spells, features, race traits… in i18n-he-*.js) go through heAdd, one
// [english, hebrew] pair per line, so a second, different translation of the same English text is
// recorded here (tools/i18n-check.js reports it) instead of silently overwriting the first.
const I18N_HE_CONFLICTS=[];
function heAdd(pairs){
  for(const [k,v] of pairs){
    if(Object.prototype.hasOwnProperty.call(I18N_HE,k)&&I18N_HE[k]!==v) I18N_HE_CONFLICTS.push({key:k,old:I18N_HE[k],new:v});
    I18N_HE[k]=v;
  }
}

